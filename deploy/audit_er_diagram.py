"""
Entity diagram of the audit database, generated from deploy/audit-schema.sql
-- so the diagram can't drift from the schema the database actually runs.

Writes:
  - the Mermaid erDiagram inside docs/audit-database.md (between the
    er-diagram markers; GitHub renders it);
  - docs/audit-er-diagram.dot, and .svg/.png rendered from it when Graphviz
    (`dot`) is installed -- for documents that can't render Mermaid.

Usage:
    python deploy/audit_er_diagram.py
    python deploy/audit_er_diagram.py --check   # exit 1 if the docs are out of date
"""

from __future__ import annotations

import argparse
import re
import shutil
import subprocess
from dataclasses import dataclass, field
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
SCHEMA = REPO_ROOT / "deploy" / "audit-schema.sql"
DOC = REPO_ROOT / "docs" / "audit-database.md"
DOT = REPO_ROOT / "docs" / "audit-er-diagram.dot"
START, END = "<!-- er-diagram:start (generated by deploy/audit_er_diagram.py) -->", "<!-- er-diagram:end -->"

_TABLE_RE = re.compile(r"CREATE TABLE IF NOT EXISTS (\w+) \((.*?)\n\);", re.DOTALL)
_KEYWORDS = {"NOT", "NULL", "DEFAULT", "REFERENCES", "UNIQUE", "PRIMARY", "GENERATED", "CHECK"}


@dataclass
class Column:
    name: str
    type: str
    pk: bool = False
    unique: bool = False
    references: str | None = None
    comment: str = ""


@dataclass
class Table:
    name: str
    columns: list[Column] = field(default_factory=list)
    unique_together: list[list[str]] = field(default_factory=list)


def parse_schema(sql: str) -> list[Table]:
    tables = []
    for name, body in _TABLE_RE.findall(sql):
        table = Table(name)
        for line in body.splitlines():
            code, _, comment = line.partition("--")
            code = code.strip().rstrip(",")
            if not code:
                continue
            if code.startswith("UNIQUE"):
                table.unique_together.append([c.strip() for c in code[code.index("(") + 1:code.rindex(")")].split(",")])
                continue
            tokens = code.split()
            type_tokens = []
            for token in tokens[1:]:
                if token.upper() in _KEYWORDS:
                    break
                type_tokens.append(token)
            ref = re.search(r"REFERENCES (\w+)", code)
            table.columns.append(Column(
                name=tokens[0],
                type=" ".join(type_tokens),
                pk="PRIMARY KEY" in code,
                unique=bool(re.search(r"\bUNIQUE\b", code)),
                references=ref.group(1) if ref else None,
                comment=comment.strip(),
            ))
        tables.append(table)
    return tables


def mermaid(tables: list[Table]) -> str:
    lines = ["erDiagram"]
    for table in tables:
        child = table.name
        for column in table.columns:
            if column.references:
                lines.append(f'    {column.references} ||--o{{ {child} : "{column.name}"')
    for table in tables:
        lines.append(f"    {table.name} {{")
        for c in table.columns:
            keys = ",".join(k for k, on in (("PK", c.pk), ("FK", bool(c.references)), ("UK", c.unique)) if on)
            comment = f' "{c.comment.replace(chr(34), chr(39))}"' if c.comment else ""
            lines.append(f"        {c.type.replace(' ', '_')} {c.name}{(' ' + keys) if keys else ''}{comment}")
        lines.append("    }")
    return "\n".join(lines)


def _html(text: str) -> str:
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;")


def graphviz(tables: list[Table]) -> str:
    lines = [
        "// Generated by deploy/audit_er_diagram.py from deploy/audit-schema.sql -- do not edit.",
        "digraph audit {",
        '    graph [rankdir=LR, fontname="Helvetica", nodesep=0.5, ranksep=1.1, label="Audit database (PostgreSQL) -- deploy/audit-schema.sql", labelloc=t, fontsize=16];',
        '    node [shape=plain, fontname="Helvetica", fontsize=11];',
        # parent (one) -> child (zero or many): parents on the left.
        '    edge [dir=both, arrowtail=teetee, arrowhead=crowodot, color="#555555"];',
    ]
    for table in tables:
        rows = [f'<tr><td bgcolor="#2f5d8a" colspan="3"><font color="white"><b>{table.name}</b></font></td></tr>']
        for c in table.columns:
            keys = " ".join(k for k, on in (("PK", c.pk), ("FK", bool(c.references)), ("UK", c.unique)) if on)
            name = f"<b>{c.name}</b>" if c.pk else c.name
            # Edges enter a row on its left cell and leave from its right one.
            rows.append(f'<tr><td port="{c.name}_in" align="left">{name}</td><td align="left">{_html(c.type)}</td>'
                        f'<td port="{c.name}_out" align="left">{keys}</td></tr>')
        for group in table.unique_together:
            rows.append(f'<tr><td colspan="3" align="left"><i>unique ({_html(", ".join(group))})</i></td></tr>')
        lines.append(f'    {table.name} [label=<<table border="0" cellborder="1" cellspacing="0" cellpadding="4">{"".join(rows)}</table>>];')
    for table in tables:
        for c in table.columns:
            if c.references:
                lines.append(f"    {c.references}:id_out:e -> {table.name}:{c.name}_in:w;")
    lines.append("}")
    return "\n".join(lines) + "\n"


def updated_doc(doc_text: str, diagram: str) -> str:
    head, _, rest = doc_text.partition(START)
    _, _, tail = rest.partition(END)
    return f"{head}{START}\n```mermaid\n{diagram}\n```\n{END}{tail}"


def main(argv=None) -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="only check that the docs match the schema")
    args = parser.parse_args(argv)
    tables = parse_schema(SCHEMA.read_text())
    doc = updated_doc(DOC.read_text(), mermaid(tables))
    dot = graphviz(tables)
    if args.check:
        stale = [str(p.relative_to(REPO_ROOT)) for p, text in ((DOC, doc), (DOT, dot)) if p.read_text() != text]
        if stale:
            raise SystemExit(f"out of date: {', '.join(stale)} -- run python deploy/audit_er_diagram.py")
        print("diagram up to date")
        return
    DOC.write_text(doc)
    DOT.write_text(dot)
    written = [DOC, DOT]
    if shutil.which("dot"):
        for fmt in ("svg", "png"):
            out = DOT.with_suffix(f".{fmt}")
            subprocess.run(["dot", f"-T{fmt}", *(["-Gdpi=150"] if fmt == "png" else []), str(DOT), "-o", str(out)], check=True)
            written.append(out)
    print("written:", ", ".join(str(p.relative_to(REPO_ROOT)) for p in written))


if __name__ == "__main__":
    main()
